const transform = () => null;

it("removes obsolete generated API namespace files on eject without deleting authored endpoints", async () => {
  const root = await fixture('{ basePath: "/docs" }');
  await eject(root);
  await writeFile(
    join(root, "src/pages/api/docs/index.ts"),
    "// User-owned endpoint\nexport const GET = () => new Response('owned');"
  );
  await writeFile(
    join(root, "src/pages/docs/api/docs/index.ts"),
    "// Generated by Blume. Do not edit.\nexport const GET = () => new Response('{}');"
  );
  await writeFile(
    join(root, "blume.config.ts"),
    'export default { basePath: "/new" }'
  );
  await eject(root);
  expect(existsSync(join(root, "src/pages/docs/api/docs/index.ts"))).toBe(
    false
  );
  expect(existsSync(join(root, "src/pages/api/docs/index.ts"))).toBe(true);
  expect(existsSync(join(root, "src/pages/new/api/docs/pages.json.ts"))).toBe(
    true
  );
});

it("keeps mounted content and custom API rest pages ahead of the JSON catch-all", async () => {
  const root = await fixture(
    '{ basePath: "/docs", deployment: { output: "server", adapter: "node" } }'
  );
  await mkdir(join(root, "docs/api"));
  await writeFile(
    join(root, "docs/api/guide.md"),
    "# API guide\nContent must remain reachable."
  );
  const contentProject = await scanProject(root);
  await generateRuntime(contentProject);
  const pages = join(contentProject.context.outDir, "src/pages");
  expect(existsSync(join(pages, "api/[...path].ts"))).toBe(true);
  expect(existsSync(join(pages, "docs/api/[...path].ts"))).toBe(false);
  expect(existsSync(join(pages, "docs/api/docs/pages.json.ts"))).toBe(true);

  await rm(join(root, "docs/api/guide.md"));
  await mkdir(join(root, "pages/docs/api"), { recursive: true });
  await writeFile(
    join(root, "pages/docs/api/[...custom].astro"),
    "---\nexport const prerender = false;\n---\nCustom API owner"
  );
  await generateRuntime(await scanProject(root));
  expect(existsSync(join(pages, "api/[...path].ts"))).toBe(true);
  expect(existsSync(join(pages, "docs/api/[...path].ts"))).toBe(false);
  const config = await readFile(
    join(contentProject.context.outDir, "astro.config.mjs"),
    "utf-8"
  );
  expect(config).toContain('"pattern":"/docs/api/[...custom]"');
});

const runRuntimeFixture = async (
  args: string[],
  timeout: number
): Promise<void> => {
  const child = Bun.spawn(
    [
      process.execPath,
      join(packageRoot(), "test/mounted-runtime.fixture.ts"),
      ...args,
    ],
    { stderr: "pipe", stdout: "pipe" }
  );
  try {
    const [code, stdout, stderr] = await Promise.race([
      Promise.all([
        child.exited,
        new Response(child.stdout).text(),
        new Response(child.stderr).text(),
      ]),
      Bun.sleep(timeout).then(() => {
        throw new Error("Mounted runtime probe timed out");
      }),
    ]);
    expect({ code, output: code === 0 ? "" : `${stdout}\n${stderr}` }).toEqual({
      code: 0,
      output: "",
    });
  } finally {
    child.kill();
  }
};

