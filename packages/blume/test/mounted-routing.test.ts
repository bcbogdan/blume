it("generates mounted Ask, artifacts and API aliases, then prunes moved and disabled endpoints", async () => {
  const root = await fixture(
    `{ basePath: "/docs/nested", deployment: { base: "/host" }, ai: { ask: { enabled: true }, mcp: { enabled: true, discovery: false, route: "/docs/mcp" } } }`
  );
  const project = await scanProject(root);
  await generateRuntime(project);
  const pages = join(project.context.outDir, "src", "pages");
  const ask = await readFile(join(pages, "docs/nested/api/ask.ts"), "utf-8");
  expect(ask).toContain('from "blume:ask-data"');
  expect(buildRuntimeData(project)).toContain(
    '"endpoint": "/host/docs/nested/api/ask"'
  );
  expect(buildAgentReadability(project)?.artifacts.askApi).toBe(
    "/host/docs/nested/api/ask"
  );
  expect(buildAgentReadability(project)?.artifacts.mcp).toEqual({
    url: "/host/docs/mcp",
  });
  expect(buildLlmsIndex(project)).not.toContain("/.well-known/mcp.json");
  expect(buildApiCatalog(project.config)).not.toContain(
    "/.well-known/mcp.json"
  );
  expect(buildHomeLinkHeader(project.config, ["/"])).toContain(
    "/host/docs/nested/openapi.json"
  );
  expect(existsSync(join(pages, "api/docs/pages.json.ts"))).toBe(true);
  expect(existsSync(join(pages, "docs/nested/api/docs/pages.json.ts"))).toBe(
    true
  );
  const spec = await readFile(
    join(pages, "docs/nested/openapi.json.ts"),
    "utf-8"
  );
  expect(spec).not.toContain("/.well-known/mcp.json");
  const endpoint = await import(join(pages, "docs/nested/llms.txt.ts"));
  const response: Response = endpoint.GET();
  expect(response.headers.get("Content-Type")).toBe(
    "text/plain; charset=utf-8"
  );
  expect(await response.text()).toContain(
    "/host/docs/nested/api/docs/pages.json"
  );
  expect(
    existsSync(join(project.context.outDir, "src/blume-mcp/discovery.ts"))
  ).toBe(false);
  project.config.basePath = "/new";
  await generateRuntime(project);
  expect(existsSync(join(pages, "docs/nested/api/ask.ts"))).toBe(false);
  expect(existsSync(join(pages, "new/api/ask.ts"))).toBe(true);
  if (project.config.ai.ask) {
    project.config.ai.ask.enabled = false;
  }
  await generateRuntime(project);
  expect(existsSync(join(pages, "new/api/ask.ts"))).toBe(false);
});

it("ejects mounted endpoints, public icon variants and a plugins-only config bridge", async () => {
  const root = await fixture(
    `{ basePath: "/docs", publicAssetBasePath: "/docs-assets", vite: { plugins: [{ name: "user", transform: () => null }] }, ai: { ask: { enabled: true, provider: "inkeep" }, mcp: { enabled: true, discovery: false } } }`
  );
  await Promise.all(
    ["icon.svg", "icon-dark.svg", "apple-icon.png"].map(async (name) => {
      const path = join(root, "public/docs-assets", name);
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, "icon");
    })
  );
  const result = await eject(root);
  expect(result.files).toContain(join(root, "src/pages/docs/api/ask.ts"));
  const ask = await readFile(join(root, "src/pages/docs/api/ask.ts"), "utf-8");
  expect(ask).not.toContain("blume:ask-data");
  expect(existsSync(join(root, "src/pages/docs/api/docs/pages.json.ts"))).toBe(
    true
  );
  expect(existsSync(join(root, "src/pages/docs/llms.txt.ts"))).toBe(true);
  const config = await readFile(join(root, "astro.config.mjs"), "utf-8");
  expect(config).toContain('assets: "docs-assets/_astro"');
  expect(config).toContain("...(blumeConfig?.vite?.plugins ?? [])");
  expect(config).toContain("loadBlumeConfig");
  expect(config).not.toContain("/.well-known/mcp.json");
  const data = JSON.parse(
    await readFile(join(root, "src/generated/data.json"), "utf-8")
  );
  expect(data.config.favicon.href).toBe("/docs-assets/icon.svg");
  expect(data.config.favicon.dark.href).toBe("/docs-assets/icon-dark.svg");
  expect(data.config.appleIcon.href).toBe("/docs-assets/apple-icon.png");
  await writeFile(
    join(root, "blume.config.ts"),
    'export default { basePath: "/new", ai: { ask: { enabled: false }, mcp: { enabled: true, discovery: false } } }'
  );
  await eject(root);
  expect(existsSync(join(root, "src/pages/docs/api/ask.ts"))).toBe(false);
});

it("preserves explicit Ask endpoints and user-owned discovery and artifact files", async () => {
  const root = await fixture(
    `{ basePath: "/docs", ai: { ask: { enabled: true, endpoint: "https://ask.test/chat" }, mcp: { enabled: true } } }`
  );
  await mkdir(join(root, "public/.well-known"), { recursive: true });
  await writeFile(join(root, "public/.well-known/mcp.json"), '{"owned":true}');
  await writeFile(join(root, "public/llms.txt"), "Owned index");
  const project = await scanProject(root);
  await generateRuntime(project);
  expect(buildAgentReadability(project)?.artifacts.askApi).toBe(
    "https://ask.test/chat"
  );
  expect(
    existsSync(join(project.context.outDir, "src/pages/docs/api/ask.ts"))
  ).toBe(false);
  expect(
    existsSync(join(project.context.outDir, "src/blume-mcp/discovery.ts"))
  ).toBe(false);
  const endpoint = await import(
    join(project.context.outDir, "src/pages/docs/llms.txt.ts")
  );
  expect(await endpoint.GET().text()).toBe("Owned index");
  project.config.deployment.site = "https://docs.test";
  project.config.deployment.base = "/host";
  expect(buildAgentReadability(project)?.artifacts.llmsTxt).toBe(
    "https://docs.test/host/docs/llms.txt"
  );
  expect(buildAgentReadability(project)?.artifacts.mcp?.discovery).toBe(
    "https://docs.test/host/.well-known/mcp.json"
  );
  project.config.ai.mcp.discovery = false;
  await generateRuntime(project);
  expect(
    await readFile(join(root, "public/.well-known/mcp.json"), "utf-8")
  ).toBe('{"owned":true}');
});
