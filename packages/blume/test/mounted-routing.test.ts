it("keeps overlapping deployment and content layers in manifests, API bodies and recovery links", async () => {
  const root = await fixture(
    '{ basePath: "/docs", deployment: { base: "/docs", site: "https://docs.test" }, ai: { ask: { enabled: true } } }'
  );
  const project = await scanProject(root);
  const manifest = buildAgentReadability(project);
  expect(manifest?.artifacts.askApi).toBe(
    "https://docs.test/docs/docs/api/ask"
  );
  expect(manifest?.artifacts.llmsTxt).toBe(
    "https://docs.test/docs/docs/llms.txt"
  );
  expect(manifest?.artifacts.markdown.pattern).toBe(
    "https://docs.test/docs/docs/{route}.md"
  );
  const data = await buildMcpData(project);
  expect(
    buildMcpDiscovery({
      base: "/docs",
      name: "Docs",
      route: "/docs/mcp",
      site: null,
      version: "1",
    }).servers[0]?.url
  ).toBe("/docs/docs/mcp");
  const index = buildPagesIndex(data);
  expect(index.pages[0]?.json).toBe(
    "https://docs.test/docs/docs/api/docs/pages/docs.json"
  );
  expect(index.pages[0]?.markdownUrl).toBe("https://docs.test/docs/docs.md");
  expect(index.pages[0]?.url).toBe("https://docs.test/docs/docs");
  const missing = pageResponse(data, "/missing");
  expect(await missing.text()).toContain(
    "https://docs.test/docs/docs/api/docs/pages.json"
  );
  const recovery = apiNotFoundResponse(
    new Request("https://docs.test/docs/docs/api/unknown"),
    data
  );
  expect(await recovery.text()).toContain(
    "https://docs.test/docs/docs/openapi.json"
  );
  expect(buildApiCatalog(project.config)).toContain(
    '"href": "https://docs.test/docs/docs"'
  );
});

